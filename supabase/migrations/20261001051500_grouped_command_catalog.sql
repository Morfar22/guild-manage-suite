  guild_id,
  command_name,
  category,
  enabled,
  cooldown_seconds,
  allowed_role_ids,
  allowed_channel_ids
)
select
  g.id,
  c.command_name,
  c.category,
  true,
  0,
  '{}'::text[],
  '{}'::text[]
from public.guilds g
cross join catalog c
on conflict (guild_id, command_name)
do update set
  category = excluded.category,
  updated_at = now();

